func msgType(m *tlb.Message) string {
	switch {
	case m == nil:
		return ""
	case m.MsgType == tlb.MsgTypeInternal:
		return "internal"
	default:
		return "externalin"
	}
}

// opOf is the 32-bit op code at the head of the body (0 = text comment), or nil.
// jettonAmount reads the token amount (and the other party's address) from a
// jetton transfer / internal_transfer / transfer_notification / burn body; nil
// for anything else or a body that doesn't parse.
func jettonAmount(m *tlb.Message) (*string, string) {
	body := m.Msg.Payload()
	if body == nil {
		return nil, ""
	}
	s, err := body.BeginParse()
	if err != nil || s.BitsLeft() < 96 {
		return nil, ""
	}
	op, _ := s.LoadUInt(32)
	switch op {
	case 0x0f8a7ea5, 0x178d4519, 0x7362d09c, 0x595f07bc:
	default:
		return nil, ""
	}
	if _, err := s.LoadUInt(64); err != nil { // query_id
		return nil, ""
	}
	amt, err := s.LoadVarUInt(16)
	if err != nil {
		return nil, ""
	}
	v := amt.String()
	if op == 0x595f07bc {
		return &v, ""
	}
	peer := ""
	if a, err := s.LoadAddr(); err == nil && a != nil && a.Type() == address.StdAddress {
		peer = a.StringRaw()
	}
	return &v, peer
}

// maxComment caps a stored comment; longer ones are cut at a rune boundary.
const maxComment = 512

// commentText is the text of a text-comment body (op 0) or of the forward payload
// of a jetton transfer_notification (op 0x7362d09c), which is how a token
// transfer's comment reaches the receiver; ” for anything else.
func commentText(m *tlb.Message) string {
	body := m.Msg.Payload()
	if body == nil {
		return ""
	}
	s, err := body.BeginParse()
	if err != nil || s.BitsLeft() < 32 {
		return ""
	}
	op, _ := s.LoadUInt(32)
	if op == 0x7362d09c {
		if _, err := s.LoadUInt(64); err != nil { // query_id
			return ""
		}
		if _, err := s.LoadVarUInt(16); err != nil { // amount
			return ""
		}
		if _, err := s.LoadAddr(); err != nil { // sender
			return ""
		}
		inRef, err := s.LoadBoolBit() // forward_payload: Either Cell ^Cell
		if err != nil {
			return ""
		}
		if inRef {
			if s, err = s.LoadRef(); err != nil {
				return ""
			}
		}
		if s.BitsLeft() < 32 {
			return ""
		}
		op, _ = s.LoadUInt(32)
	}
	if op != 0 {
		return ""
	}
	text, err := s.LoadStringSnake()
	if err != nil || !utf8.ValidString(text) {
		return ""
	}
	if len(text) > maxComment {
		text = text[:maxComment]
		for !utf8.ValidString(text) {
			text = text[:len(text)-1]
		}
	}
	return text
}

func opOf(m *tlb.Message) *uint32 {
	var body = m.Msg.Payload()
	if body == nil {
		return nil
	}
	s, err := body.BeginParse()
	if err != nil || s.BitsLeft() < 32 {
		return nil
	}
	v, err := s.LoadUInt(32)
	if err != nil {
		return nil
	}
	op := uint32(v)
	return &op
}

// descField reads a field that several transaction description types share
// (Aborted, ComputePhase); zero Value when this type has none.
func descField(desc any, name string) reflect.Value {
	v := reflect.ValueOf(desc)
	for v.Kind() == reflect.Pointer || v.Kind() == reflect.Interface {
		if v.IsNil() {
			return reflect.Value{}
		}
		v = v.Elem()
	}
	if v.Kind() != reflect.Struct {
		return reflect.Value{}
	}
	return v.FieldByName(name)
}

func isTickTock(tx *tlb.Transaction) bool {
	switch tx.Description.(type) {
	case tlb.TransactionDescriptionTickTock, *tlb.TransactionDescriptionTickTock:
		return true
	}
	return false
}

// exitCode is the compute phase's exit code; when the phase was skipped there
// is none and skip is why (NO_STATE, BAD_STATE, NO_GAS, SUSPENDED).
func exitCode(tx *tlb.Transaction) (code *int32, skip string) {
	f := descField(tx.Description, "ComputePhase")
	if !f.IsValid() {
		return nil, ""
	}
	cp, ok := f.Interface().(tlb.ComputePhase)
	if !ok {
		return nil, ""
	}
	switch p := cp.Phase.(type) {
	case tlb.ComputePhaseVM:
		return &p.Details.ExitCode, ""
	case *tlb.ComputePhaseVM:
		return &p.Details.ExitCode, ""
	case tlb.ComputePhaseSkipped:
		return nil, string(p.Reason.Type)
	case *tlb.ComputePhaseSkipped:
		return nil, string(p.Reason.Type)
	}
	return nil, ""
}

// actionCode is the action phase's result code, nil when it didn't run.
func actionCode(tx *tlb.Transaction) *int32 {
	f := descField(tx.Description, "ActionPhase")
	if !f.IsValid() {
		return nil
	}
	if ap, ok := f.Interface().(*tlb.ActionPhase); ok && ap != nil {
		return &ap.ResultCode
	}
	return nil
}

func txRow(blk *ton.BlockIDExt, mcSeqno uint32, tx *tlb.Transaction, trace *big.Int) row {
	r := row{
		Now:        tx.Now,
		McSeqno:    mcSeqno,
		Workchain:  blk.Workchain,
		BlockSeqno: blk.SeqNo,
		Account:    fmt.Sprintf("%d:%x", blk.Workchain, tx.AccountAddr),
		LT:         tx.LT,
		InMsgType:  msgType(tx.IO.In),
		TotalFees:  tx.TotalFees.Coins.Nano().Uint64(),
		Success:    1,
		ActionCode: actionCode(tx),
		OutMsgs:    tx.OutMsgCount,
		OrigStatus: statuses[tx.OrigStatus],
		EndStatus:  statuses[tx.EndStatus],
		TraceID:    trace.String(),
	}
	r.ExitCode, r.SkipReason = exitCode(tx)
	fees(tx, &r)
	if a := descField(tx.Description, "Aborted"); a.IsValid() && a.Bool() {
		r.Success = 0
	}
	if in := tx.IO.In; in != nil {
		r.Op = opOf(in)
		r.JettonAmt, r.JettonPeer = jettonAmount(in)
		r.Comment = commentText(in)
		r.InitCode = initCodeHash(in)
		if in.MsgType == tlb.MsgTypeInternal {
			m := in.AsInternal()
			r.Bounce, r.Bounced = b2u(m.Bounce), b2u(m.Bounced)
			r.Src = m.SrcAddr.StringRaw()
			r.Value = m.Amount.Nano().Uint64()
		}
	}
	return r
}

