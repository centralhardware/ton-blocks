// Command ton-blocks logs every new TON block's transactions to ClickHouse, for analytics.
//
// No node of our own: the blocks are read from the public mainnet liteservers
// (the global config at ton.org), parsed here with tonutils-go, and stored. A
// block *is* the diff, so nothing needs the chain state.
//
// How one masterchain block is handled:
//
//	mc block N        -> its own transactions (workchain -1)
//	shard tops of N   -> each one, then its predecessors walked back through
//	                     the prev refs until we reach what the shard tops of
//	                     N-1 already covered (several shard blocks can land
//	                     between two mc blocks, and shards split and merge)
//
// Only what analytics needs is kept: no per-block rows, no masterchain
// tick-tock housekeeping, and no hashes except `trace_id` -- the hash of the
// transaction that started the trace (the external message a user signed),
// shared by every transaction that message set off, so one user action can be
// grouped. It is the id the explorers use: tonviewer.com/transaction/<hex>.
// 0 = unknown (the parent was seen before the last restart, or is older than
// traceKeep).
//
// The schema is in migrations/*.sql (see migrate). Every row carries the
// mc_seqno it arrived with, and a restart resumes from max(mc_seqno) + 1, so an
// outage backfills the gap instead of skipping it. Each flush is a single
// INSERT, so the summary views count every batch once.
//
//	ton-blocks                      apply migrations, then follow the chain
//	ton-blocks -init                only apply the migrations
//	ton-blocks -print-ddl           the migrations' statements
//	ton-blocks -from 100400000      start/backfill from that mc seqno
//	ton-blocks -dry-run -count 3    process 3 mc blocks, print, touch nothing
//	ton-blocks -healthcheck         exit 1 when the heartbeat is stale (Docker)
//
// Configured by environment: CLICKHOUSE_URL, CLICKHOUSE_TON_USER,
// CLICKHOUSE_TON_PASSWORD, and optionally TONCENTER_API_KEY (jetton lookups,
// see jettons.go). The login needs SELECT, INSERT, CREATE TABLE, CREATE
// VIEW, ALTER and DROP TABLE on `ton.*` (the last two for migrations that change
// a table); the `ton` database itself is created by an admin.
