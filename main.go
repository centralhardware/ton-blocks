func post(query string, body []byte) (string, error) {
	base := os.Getenv("CLICKHOUSE_URL")
	if base == "" {
		return "", errors.New("CLICKHOUSE_URL not set")
	}
	params := url.Values{
		"user":     {os.Getenv("CLICKHOUSE_TON_USER")},
		"password": {os.Getenv("CLICKHOUSE_TON_PASSWORD")},
		"database": {database},
	}
	data := []byte(query)
	if body != nil {
		params.Set("query", query)
		data = body
	}
	client := http.Client{Timeout: httpTimeout}
	resp, err := client.Post(strings.TrimRight(base, "/")+"/?"+params.Encode(), "text/plain", bytes.NewReader(data))
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	out, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("ClickHouse %d: %.600s", resp.StatusCode, out)
	}
	return string(out), nil
}

func insert(table string, rows any) error {
	v := reflect.ValueOf(rows)
	if v.Len() == 0 {
		return nil
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	for i := 0; i < v.Len(); i++ {
		if err := enc.Encode(v.Index(i).Interface()); err != nil {
			return err
		}
	}
	_, err := post(fmt.Sprintf("INSERT INTO %s.%s FORMAT JSONEachRow", database, table), buf.Bytes())
	return err
}

type migration struct {
	version int
	name    string
	stmts   []string
}

var (
	stmtEnd = regexp.MustCompile(`;[ \t]*\n`)
	comment = regexp.MustCompile(`--[^\n]*`)
)

func migrations() ([]migration, error) {
	entries, err := files.ReadDir("migrations")
	if err != nil {
		return nil, err
	}
	var out []migration
	for _, e := range entries { // ReadDir returns them sorted by name
		v, err := strconv.Atoi(e.Name()[:4])
		if err != nil {
			continue
		}
		text, err := files.ReadFile("migrations/" + e.Name())
		if err != nil {
			return nil, err
		}
		m := migration{version: v, name: e.Name()}
		for _, s := range stmtEnd.Split(string(text), -1) {
			if s = strings.TrimSpace(s); strings.TrimSpace(comment.ReplaceAllString(s, "")) != "" {
				m.stmts = append(m.stmts, s)
			}
		}
		out = append(out, m)
	}
	return out, nil
}

type migrationRow struct {
	Version int    `json:"version"`
	Name    string `json:"name"`
}

// migrate applies the migrations not yet recorded in schema_migrations, in order.
func migrate() error {
	if _, err := post("CREATE TABLE IF NOT EXISTS "+database+".schema_migrations (version UInt32, name String,"+
		" applied_at DateTime('UTC') DEFAULT now()) ENGINE = MergeTree ORDER BY version", nil); err != nil {
		return err
	}
	out, err := post("SELECT version FROM "+database+".schema_migrations FORMAT TSV", nil)
	if err != nil {
		return err
	}
	done := map[int]bool{}
	for _, f := range strings.Fields(out) {
		v, _ := strconv.Atoi(f)
		done[v] = true
	}
	todo, err := migrations()
	if err != nil {
		return err
	}
	if len(done) == 0 {
		exists, err := post("EXISTS TABLE "+database+".transactions FORMAT TSV", nil)
		if err != nil {
			return err
		}
		if strings.TrimSpace(exists) == "1" {
			var base []migrationRow
			for _, m := range todo {
				if m.version <= baseline {
					base = append(base, migrationRow{m.version, m.name})
					done[m.version] = true
				}
			}
			if err := insert("schema_migrations", base); err != nil {
				return err
			}
			log.Printf("existing schema marked at migration %04d", baseline)
		}
	}
	for _, m := range todo {
		if done[m.version] {
			continue
		}
		for _, s := range m.stmts {
			if _, err := post(s, nil); err != nil {
				return fmt.Errorf("%s: %w", m.name, err)
			}
		}
		if err := insert("schema_migrations", []migrationRow{{m.version, m.name}}); err != nil {
			return err
		}
		log.Printf("applied migration %s", m.name)
	}
	return nil
}

type opName struct {
	Op          int64  `json:"op"`
	Name        string `json:"name"`
	Protocol    string `json:"protocol"`
	Description string `json:"description"`
	Source      string `json:"source"`
}

// loadOpNames re-inserts the op name files on every start; ReplacingMergeTree
// keeps the newest row per op, so editing a file and redeploying updates the
// names. op is stored like ops_hour.op: -1 = no body.
func loadOpNames() error {
	var rows []opName
	for _, path := range []string{"op_names.tsv", "op_names_registry.tsv"} {
		data, err := files.ReadFile(path)
		if err != nil {
			return err
		}
		lines := strings.Split(string(data), "\n")
		header := strings.Split(lines[0], "\t")
		for _, line := range lines[1:] {
			if strings.TrimSpace(line) == "" {
				continue
			}
			r := map[string]string{}
			for i, v := range strings.Split(line, "\t") {
				if i < len(header) {
					r[header[i]] = v
				}
			}
			op, err := strconv.ParseInt(r["op"], 0, 64)
			if err != nil {
				return fmt.Errorf("%s: bad op %q", path, r["op"])
			}
			rows = append(rows, opName{op, r["name"], r["protocol"], r["description"], r["source"]})
		}
	}
	if err := insert("op_names", rows); err != nil {
		return err
	}
	log.Printf("op_names: %d entries", len(rows))
	return nil
}

// missingMcSeqnos returns the mc seqnos in [lo, hi) with no row in the
// destination table. Every mc block carries at least one non-tick-tock
// transaction (the fee-minting message from -1:000..), so an absent seqno is a
// lost one, not an empty one.
func missingMcSeqnos(lo, hi uint32) ([]uint32, error) {
	if hi <= lo {
		return nil, nil
	}
	out, err := post(fmt.Sprintf("SELECT number FROM numbers(%d, %d) WHERE number NOT IN "+
		"(SELECT DISTINCT mc_seqno FROM %s.transactions WHERE mc_seqno >= %d AND mc_seqno < %d) "+
		"ORDER BY number FORMAT TSV", lo, hi-lo, database, lo, hi), nil)
	if err != nil {
		return nil, err
	}
	var res []uint32
	for _, f := range strings.Fields(out) {
		v, _ := strconv.ParseUint(f, 10, 32)
		res = append(res, uint32(v))
	}
	return res, nil
}

// resumePoint is the mc seqno after the last one stored, or 0 on an empty table.
func resumePoint() (uint32, error) {
	// reading the Buffer table reads the destination plus whatever is still buffered
	out, err := post("SELECT max(mc_seqno), count() FROM "+database+"."+insertTable+" FORMAT TSV", nil)
	if err != nil {
		return 0, err
	}
	f := strings.Fields(out)
	if len(f) != 2 || f[1] == "0" {
		return 0, nil
	}
	top, err := strconv.ParseUint(f[0], 10, 32)
	return uint32(top) + 1, err
}

