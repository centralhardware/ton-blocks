type follower struct {
	api      ton.APIClientWrapped
	dryRun   bool
	prevTops []*ton.BlockIDExt // shard tops of the last processed mc block
	rows     []row
	traces   map[string]traced // out message hash -> its trace
	lastSave time.Time
	blocks   []blockRow // flushed every blocksEvery: a few rows a second only
	swaps    []swapRow  // likewise
	outs     []outRow   // flushed with rows
	blocksAt time.Time
	mcSeqno  uint32 // the mc block being processed
}

func connect(ctx context.Context) (ton.APIClientWrapped, error) {
	pool := liteclient.NewConnectionPool()
	if err := pool.AddConnectionsFromConfigUrl(ctx, mainnetConfig); err != nil {
		return nil, err
	}
	// blocks are looked up by seqno and checked against their hashes by the
	// liteserver; no proof chain from a trusted block is needed for logging
	return ton.NewAPIClient(pool, ton.ProofCheckPolicyFast).WithTimeout(requestTimeout), nil
}

func (f *follower) mcID(ctx context.Context, seqno uint32) (*ton.BlockIDExt, error) {
	return f.api.LookupBlock(ctx, -1, math.MinInt64, seqno)
}

// oneBlock collects one block's transactions; returns the blocks it was built on.
func (f *follower) oneBlock(ctx context.Context, blk *ton.BlockIDExt, txs *[]blockTx) ([]*ton.BlockIDExt, error) {
	data, err := f.api.GetBlockData(ctx, blk)
	if err != nil {
		return nil, err
	}
	list, err := data.ListTransactions()
	if err != nil {
		return nil, err
	}
	for _, t := range list {
		*txs = append(*txs, blockTx{blk, t})
	}
	f.blocks = append(f.blocks, newBlockRow(f.mcSeqno, blk, data, len(list)))
	return ton.GetParentBlocks(&data.BlockInfo)
}

func overlaps(a, b uint64) bool {
	// two shard ids of one workchain cover intersecting address ranges: the
	// coarser one's prefix bits must match the finer one's
	la, lb := a&-a, b&-b
	big := max(la, lb)
	mask := ^((big << 1) - 1)
	return a&mask == b&mask
}

func covered(b *ton.BlockIDExt, prevTops []*ton.BlockIDExt) bool {
	for _, t := range prevTops {
		if t.Workchain == b.Workchain && overlaps(uint64(t.Shard), uint64(b.Shard)) && t.SeqNo >= b.SeqNo {
			return true
		}
	}
	return false
}

// traceRows builds the rows for one mc block's transactions, each tagged with
// its trace. A child's lt is always above its parent's, so in lt order every
// parent in this mc block is linked before its children; parents from earlier
// mc blocks come from f.traces. Tick-tock transactions are linked (their
// messages start traces too) but not stored.
//
// Message hashes are taken from re-serialized messages on both sides (sender's
// out list, receiver's in message), so they always agree with each other.
func (f *follower) traceRows(mcSeqno uint32, txs []blockTx) ([]row, error) {
	sort.Slice(txs, func(i, j int) bool { return txs[i].tx.LT < txs[j].tx.LT })
	var rows []row
	for _, bt := range txs {
		t := bt.tx
		var trace *big.Int
		if in := t.IO.In; in == nil || in.MsgType != tlb.MsgTypeInternal {
			trace = new(big.Int).SetBytes(t.Hash)
		} else {
			c, err := in.ToCell()
			if err != nil {
				return nil, err
			}
			key := string(c.Hash())
			if p, ok := f.traces[key]; ok {
				trace = p.trace
				delete(f.traces, key)
			} else {
				trace = new(big.Int)
			}
		}
		if t.IO.Out != nil {
			outs, err := t.IO.Out.ToSlice()
			if err != nil {
				return nil, err
			}
			for i := range outs {
				if outs[i].MsgType != tlb.MsgTypeInternal {
					continue
				}
				c, err := outs[i].ToCell()
				if err != nil {
					return nil, err
				}
				f.traces[string(c.Hash())] = traced{trace, mcSeqno}
			}
		}
		if !isTickTock(t) {
			r := txRow(bt.blk, mcSeqno, t, trace)
			rows = append(rows, r)
			f.outs = append(f.outs, outRows(t, r.Account, mcSeqno, trace)...)
			if sw := swapOf(t); sw != nil {
				sw.Now, sw.McSeqno, sw.TraceID = t.Now, mcSeqno, trace.String()
				sw.Pool = fmt.Sprintf("%d:%x", bt.blk.Workchain, t.AccountAddr)
				f.swaps = append(f.swaps, *sw)
			}
		}
	}
	if mcSeqno%100 == 0 {
		for k, v := range f.traces {
			if v.seqno+traceKeep < mcSeqno {
				delete(f.traces, k)
			}
		}
	}
	return rows, nil
}

// process stores one mc block and every shard block it brought in. Rows reach
// the buffer only once the whole mc block succeeded: a retry after a half-done
// block must not insert its first blocks twice (the table would dedupe them on
// merge, the summary views would not).
func (f *follower) process(ctx context.Context, seqno uint32) (_ int, err error) {
	var txs []blockTx
	f.mcSeqno = seqno
	nBlocks, nSwaps, nOuts := len(f.blocks), len(f.swaps), len(f.outs)
	defer func() {
		if err != nil { // the mc block is retried whole; drop its partial block rows
			f.blocks, f.swaps = f.blocks[:nBlocks], f.swaps[:nSwaps]
			f.outs = f.outs[:nOuts]
		}
	}()
	mc, err := f.mcID(ctx, seqno)
	if err != nil {
		return 0, err
	}
	if _, err := f.oneBlock(ctx, mc, &txs); err != nil {
		return 0, err
	}
	tops, err := f.api.GetBlockShardsInfo(ctx, mc)
	if err != nil {
		return 0, err
	}
	prevTops := f.prevTops
	if prevTops == nil {
		prev, err := f.mcID(ctx, seqno-1)
		if err != nil {
			return 0, err
		}
		if prevTops, err = f.api.GetBlockShardsInfo(ctx, prev); err != nil {
			return 0, err
		}
	}
	seen := map[string]bool{}
	queue := append([]*ton.BlockIDExt(nil), tops...)
	for len(queue) > 0 {
		b := queue[len(queue)-1]
		queue = queue[:len(queue)-1]
		key := fmt.Sprintf("%d:%d:%d", b.Workchain, b.Shard, b.SeqNo)
		if seen[key] || covered(b, prevTops) {
			continue
		}
		seen[key] = true
		parents, err := f.oneBlock(ctx, b, &txs)
		if err != nil {
			return 0, err
		}
		queue = append(queue, parents...)
	}
	rows, err := f.traceRows(seqno, txs)
	if err != nil {
		return 0, err
	}
	f.rows = append(f.rows, rows...)
	f.prevTops = tops
	return len(seen) + 1, nil
}

func (f *follower) flush(force bool) error {
	if len(f.blocks) > 0 && (force || time.Since(f.blocksAt) >= blocksEvery) {
		if f.dryRun {
			first, _ := json.Marshal(f.blocks[0])
			log.Printf("blocks: %d (first: %s)", len(f.blocks), first)
		} else if err := insert("block_log", f.blocks); err != nil {
			return err
		}
		if !f.dryRun {
			if err := insert("swaps", f.swaps); err != nil {
				return err
			}
		} else if len(f.swaps) > 0 {
			first, _ := json.Marshal(f.swaps[0])
			log.Printf("swaps: %d (first: %s)", len(f.swaps), first)
		}
		f.blocks, f.swaps = nil, nil
		f.blocksAt = time.Now()
	}
	due := force || len(f.rows) >= flushRows || time.Since(f.lastSave) >= flushEvery
	if !due || len(f.rows) == 0 {
		return nil
	}
	if f.dryRun {
		first, _ := json.Marshal(f.rows[0])
		log.Printf("transactions: %d (first: %s)", len(f.rows), first)
		if len(f.outs) > 0 {
			first, _ = json.Marshal(f.outs[len(f.outs)-1])
			log.Printf("out messages: %d (last: %s)", len(f.outs), first)
		}
	} else {
		// out messages first: if the transactions insert then fails, the retry
		// inserts them again and ReplacingMergeTree drops the duplicates
		if err := insert("out_messages_buffer", f.outs); err != nil {
			return err
		}
		f.outs = nil
		if err := insert(insertTable, f.rows); err != nil {
			// one INSERT per flush, so the minute view sees each batch exactly once;
			// on failure the rows stay and go with the next flush
			return err
		}
	}
	f.rows, f.outs = nil, nil
	f.lastSave = time.Now()
	return nil
}

func isNotInDB(err error) bool {
	var ls ton.LSError
	if errors.As(err, &ls) {
		return ls.Code == 651
	}
	var lsp *ton.LSError
	return errors.As(err, &lsp) && lsp.Code == 651
}

func run(ctx context.Context, start uint32, count int, dryRun, verbose bool) error {
	api, err := connect(ctx)
	if err != nil {
		return err
	}
	f := &follower{api: api, dryRun: dryRun, traces: map[string]traced{}, lastSave: time.Now()}
	nxt := start
	if nxt == 0 && !dryRun {
		if nxt, err = resumePoint(); err != nil {
			return err
		}
	}
	if nxt == 0 {
		head, err := api.GetMasterchainInfo(ctx)
		if err != nil {
			return err
		}
		nxt = head.SeqNo - confirmations
	}
	log.Printf("following from mc seqno %d", nxt)
	done, failures, transient := 0, 0, 0
	first, lastCheck, lastNote := nxt, time.Now(), time.Now()
	for count == 0 || done < count {
		err := func() error {
			head, err := api.GetMasterchainInfo(ctx)
			if err != nil {
				return err
			}
			if nxt+confirmations > head.SeqNo {
				time.Sleep(pollEvery)
				return f.flush(false)
			}
			n, err := f.process(ctx, nxt)
			if err != nil {
				return err
			}
			if dryRun || verbose {
				log.Printf("mc %d: %d blocks, lag %d", nxt, n, head.SeqNo-nxt)
			}
			nxt++
			done++
			now := time.Now()
			_ = os.Chtimes(heartbeat, now, now)
			if _, err := os.Stat(heartbeat); err != nil {
				_ = os.WriteFile(heartbeat, nil, 0o644)
			}
			failures = 0
			if err := f.flush(false); err != nil {
				return err
			}
			if !dryRun && time.Since(lastCheck) >= continuityEvery {
				// rows a ClickHouse crash dropped from the buffer: fetch those mc blocks again
				lastCheck = time.Now()
				lo := first
				if nxt > continuityWindow && nxt-continuityWindow > lo {
					lo = nxt - continuityWindow
				}
				lost, err := missingMcSeqnos(lo, nxt-continuitySettle)
				if err != nil {
					return err
				}
				if len(lost) > 0 {
					log.Printf("refetching %d lost mc blocks (%d..%d)", len(lost), lost[0], lost[len(lost)-1])
					if err := f.flush(true); err != nil {
						return err
					}
					for _, s := range lost {
						f.prevTops = nil
						if _, err := f.process(ctx, s); err != nil {
							return err
						}
					}
					f.prevTops = nil
					return f.flush(true)
				}
			}
			return nil
		}()
		if err == nil {
			continue
		}
		f.prevTops = nil
		if isNotInDB(err) {
			// a liteserver behind the others: just ask again (the pool picks
			// another one); counted and reported once a minute
			transient++
			if time.Since(lastNote) >= time.Minute {
				log.Printf("%d transient 'not in db' retries in the last minute", transient)
				transient, lastNote = 0, time.Now()
			}
			time.Sleep(transientRetry)
			continue
		}
		// a dropped liteserver or a ClickHouse hiccup: rows not yet flushed stay
		// buffered, the mc block is retried with backoff
		failures++
		wait := time.Duration(min(60, 1<<min(failures, 6))) * time.Second
		log.Printf("mc %d failed (%v), retry in %s", nxt, err, wait)
		time.Sleep(wait)
	}
	return f.flush(true)
}

func healthy() bool {
	st, err := os.Stat(heartbeat)
	return err == nil && time.Since(st.ModTime()) < 3*time.Minute
}

func main() {
	log.SetFlags(0)
	printDDL := flag.Bool("print-ddl", false, "print the migrations' statements")
	initOnly := flag.Bool("init", false, "only apply the migrations")
	from := flag.Uint("from", 0, "start/backfill from this mc seqno")
	count := flag.Int("count", 0, "stop after this many mc blocks")
	dryRun := flag.Bool("dry-run", false, "print rows, touch nothing")
	verbose := flag.Bool("v", false, "log every mc block")
	health := flag.Bool("healthcheck", false, "exit 1 when no mc block was processed for 3 minutes")
	flag.Parse()

	if *health {
		if !healthy() {
			os.Exit(1)
		}
		return
	}
	if *printDDL {
		ms, err := migrations()
		if err != nil {
			log.Fatal(err)
		}
		fmt.Printf("CREATE DATABASE IF NOT EXISTS %s;\n\n", database)
		for _, m := range ms {
			fmt.Printf("-- %s\n", m.name)
			for _, s := range m.stmts {
				fmt.Printf("%s;\n\n", s)
			}
		}
		return
	}
	if *initOnly || !*dryRun {
		if err := migrate(); err != nil {
			log.Fatal(err)
		}
		if err := loadOpNames(); err != nil {
			log.Fatal(err)
		}
		log.Print("tables ready")
		if *initOnly {
			return
		}
		go resolveJettons()
		go resolveContracts()
	}
	if err := run(context.Background(), uint32(*from), *count, *dryRun, *verbose); err != nil {
		log.Fatal(err)
	}
}
